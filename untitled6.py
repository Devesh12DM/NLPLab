X_test = vectorizer.transform(pages)

# Predict probabilities
probabilities = model.predict_proba(X_test)

states = model.classes_

n = len(states)

# Transition probabilities
transition = np.full((n, n), 0.05 / (n - 1))

np.fill_diagonal(transition, 0.95)

initial = np.ones(n) / n

def viterbi(prob):

    T, N = prob.shape

    dp = np.zeros((T, N))
    back = np.zeros((T, N), dtype=int)

    dp[0] = np.log(initial) + np.log(prob[0] + 1e-10)

    for t in range(1, T):
        for j in range(N):

            score = dp[t-1] + np.log(transition[:, j])

            back[t, j] = np.argmax(score)

            dp[t, j] = (
                np.max(score) +
                np.log(prob[t, j] + 1e-10)
            )

    last = np.argmax(dp[-1])

    path = [last]

    for t in range(T-1, 0, -1):
        last = back[t, last]
        path.append(last)

    path.reverse()

    return [states[i] for i in path]


result = viterbi(probabilities)

